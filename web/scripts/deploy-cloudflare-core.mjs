function clean(value) {
  const normalized = String(value ?? "").trim();
  return normalized === "undefined" || normalized === "null" ? "" : normalized;
}

export function assertCloudflareControlEnvironment(env = {}) {
  const rawAccount = String(env.CLOUDFLARE_ACCOUNT_ID ?? "");
  const suppliedAccount = rawAccount.toLowerCase();
  if (suppliedAccount && suppliedAccount !== CLOUDFLARE_ACCOUNT_ID) {
    throw new Error("Cloudflare release environment targets an account other than the reviewed account");
  }
  for (const key of FORBIDDEN_CLOUDFLARE_CONTROL_ENV) {
    // Do not normalize sentinel-looking or whitespace-only strings away:
    // Wrangler and its HTTP clients treat any non-empty raw value as supplied.
    if (String(env[key] ?? "").length > 0) {
      throw new Error(`Cloudflare release refuses the ${key} control override`);
    }
  }
  const token = String(env.CLOUDFLARE_API_TOKEN ?? "");
  const globalKey = String(env.CLOUDFLARE_API_KEY ?? "");
  const globalEmail = String(env.CLOUDFLARE_EMAIL ?? "");
  if (Boolean(globalKey) !== Boolean(globalEmail)) {
    throw new Error("Cloudflare release requires a complete global key/email credential pair");
  }
  if (token && globalKey) {
    throw new Error("Cloudflare release refuses ambiguous API token and global-key credentials");
  }
}

export function cloudflareWranglerEnvironment(env = {}) {
  assertCloudflareControlEnvironment(env);
  const child = {};
  for (const key of WRANGLER_CHILD_ENV_ALLOWLIST) {
    if (Object.prototype.hasOwnProperty.call(env, key)) {
      child[key] = String(env[key] ?? "");
    }
  }
  // The target account is a release invariant, never inherited authority.
  child.PATH = RELEASE_CHILD_PATH;
  child.CLOUDFLARE_ACCOUNT_ID = CLOUDFLARE_ACCOUNT_ID;
  // Keep diagnostics local and bounded rather than allowing Wrangler to send
  // release failures or usage events alongside the deployment.
  child.WRANGLER_SEND_METRICS = "false";
  child.WRANGLER_SEND_ERROR_REPORTS = "false";
  child.WRANGLER_LOG_SANITIZE = "true";
  child.WRANGLER_WRITE_LOGS = "false";
  return Object.freeze(child);
}

export function cloudflareBuildEnvironment(releaseEnv = {}, _hostEnv = {}, isolatedHome) {
  if (
    typeof isolatedHome !== "string"
    || !path.isAbsolute(isolatedHome)
    || path.resolve(isolatedHome) !== isolatedHome
    || path.normalize(isolatedHome) !== isolatedHome
  ) {
    throw new Error("Cloudflare verification requires a canonical absolute isolated HOME");
  }
  const child = {
    PATH: RELEASE_CHILD_PATH,
    LANG: "C",
    LC_ALL: "C",
    TZ: "UTC",
    CI: "true",
    NO_COLOR: "1",
    TERM: "dumb",
  };
  for (const [key, value] of Object.entries(releaseEnv || {})) {
    if (key.startsWith("VITE_")) child[key] = String(value ?? "");
  }
  child.HOME = isolatedHome;
  child.TMPDIR = path.join(isolatedHome, "tmp");
  child.XDG_CACHE_HOME = path.join(isolatedHome, ".cache");
  child.XDG_CONFIG_HOME = path.join(isolatedHome, ".config");
  child.XDG_DATA_HOME = path.join(isolatedHome, ".local", "share");
  child.NODE_ENV = "production";
  child.NPM_CONFIG_AUDIT = "false";
  child.NPM_CONFIG_CACHE = path.join(isolatedHome, ".npm-cache");
  child.NPM_CONFIG_FUND = "false";
  child.NPM_CONFIG_UPDATE_NOTIFIER = "false";
  child.NPM_CONFIG_USERCONFIG = path.join(isolatedHome, ".npmrc");
  return Object.freeze(child);
}

export function cloudflareReleaseIntent(env) {
  for (const key of FORBIDDEN_RELEASE_ENV_KEYS) {
    if (Object.prototype.hasOwnProperty.call(env || {}, key)) {
      throw new Error(`Cloudflare release refuses the legacy or ambiguous ${key} binding`);
    }
  }
  const liveFeatureRequested = LIVE_FEATURE_FLAGS.some((key) => clean(env[key]) === "true");
  const releaseBindingPresent = RELEASE_BINDINGS.some((key) => clean(env[key]) !== "");
  return liveFeatureRequested || releaseBindingPresent ? "live" : "modeled";
}

function assertModeledEnvironmentHasNoViteOverrides(env) {
  const viteKeys = Object.keys(env || {}).filter((key) => key.startsWith("VITE_"));
  if (viteKeys.length) {
    throw new Error(
      "modeled Cloudflare preview requires an empty VITE_ environment; release bindings must come only from the canonical live validator",
    );
  }
}

function canonicalEffectiveReleaseEnv(env) {
  const values = {};
  for (const [key, value] of Object.entries(env || {})) {
    if (key.startsWith("VITE_")) values[key] = String(value ?? "");
  }
  return serializeEnv(values);
}

function assertExactComputeWorkloadBindings(env) {
  const address = /^0x(?!0{40}$)[0-9a-f]{40}$/;
  const bytes32 = /^0x(?!0{64}$)[0-9a-f]{64}$/;
  const bareBytes32 = /^(?!0{64}$)[0-9a-f]{64}$/;
  const appId = /^(?!0{40}$)[0-9a-f]{40}$/;
  const cvmId = /^[a-z0-9][a-z0-9._:-]{7,127}$/;
  const sha256Pin = /^sha256:(?!0{64}$)[0-9a-f]{64}$/;
  for (const [key, pattern] of [
    ["VITE_COMPUTE_WORKLOAD_QVL_VERIFIER", address],
    ["VITE_COMPUTE_WORKLOAD_CVM_ID", cvmId],
    ["VITE_COMPUTE_WORKLOAD_DEPLOYMENT_INTENT_SHA256", sha256Pin],
    ["VITE_COMPUTE_WORKLOAD_RELEASE_AUTHORITY_SHA256", sha256Pin],
    ["VITE_COMPUTE_WORKLOAD_CEREMONY_NONCE", bytes32],
    ["VITE_COMPUTE_WORKLOAD_MEASUREMENT_POLICY_SET_SHA256", sha256Pin],
    ["VITE_COMPUTE_WORKLOAD_MEASUREMENT_POLICY_SHA256", sha256Pin],
    ["VITE_COMPUTE_WORKLOAD_MAIN_RUNTIME_EVIDENCE_SHA256", sha256Pin],
    ["VITE_COMPUTE_WORKLOAD_QVL_RELEASE_POLICY_HASH", bytes32],
    ["VITE_COMPUTE_WORKLOAD_COMPOSE_HASH", bytes32],
    ["VITE_COMPUTE_WORKLOAD_APP_ID", appId],
    ["VITE_COMPUTE_WORKLOAD_OS_IMAGE_HASH", bareBytes32],
    ["VITE_COMPUTE_WORKLOAD_ACTIVATION_SIGNER", address],
    ["VITE_COMPUTE_WORKLOAD_CONTRACT_ADDRESS", address],
    ["VITE_COMPUTE_WORKLOAD_VAULT_RUNTIME_CODE_HASH", bytes32],
    ["VITE_COMPUTE_WORKLOAD_FRESH_DEPLOYMENT_RECEIPT_SHA256", bytes32],
  ]) {
    if (!pattern.test(String(env[key] || ""))) {
      throw new Error(`live Cloudflare release requires exact canonical ${key}`);
    }
  }
  if (clean(env.VITE_COMPUTE_WORKLOAD_CHAIN_ID) !== String(BASE_SEPOLIA_CHAIN_ID)) {
    throw new Error("live Cloudflare compute workload must target Base Sepolia");
  }
  if (
    clean(env.VITE_COMPUTE_WORKLOAD_CONTRACT_ADDRESS).toLowerCase()
      !== clean(env.VITE_COMPUTE_CREDIT_VAULT_ADDRESS).toLowerCase()
  ) {
    throw new Error("live Cloudflare compute workload contract does not match ComputeCreditVault");
  }
  if (
    clean(env.VITE_COMPUTE_WORKLOAD_VAULT_RUNTIME_CODE_HASH).toLowerCase()
      !== clean(env.VITE_COMPUTE_CREDIT_VAULT_CODE_HASH).toLowerCase()
  ) {
    throw new Error("live Cloudflare compute workload runtime does not match ComputeCreditVault");
  }
  if (
    env.VITE_COMPUTE_WORKLOAD_FRESH_DEPLOYMENT_RECEIPT_SHA256
      === env.VITE_COMPUTE_WORKLOAD_VAULT_RUNTIME_CODE_HASH
  ) {
    throw new Error("live Cloudflare workload deployment receipt cannot collapse into runtime code");
  }
  const maximumAge = Number(env.VITE_COMPUTE_WORKLOAD_MAX_VERDICT_AGE_SECONDS);
  if (
    !/^(?:[1-9]|[1-9][0-9]|[12][0-9]{2}|300)$/.test(
      String(env.VITE_COMPUTE_WORKLOAD_MAX_VERDICT_AGE_SECONDS || ""),
    )
    || !Number.isSafeInteger(maximumAge)
    || maximumAge < 1
    || maximumAge > 300
  ) {
    throw new Error("live Cloudflare workload verdict age must be 1 through 300 seconds");
  }
  let revoked;
  try {
    revoked = JSON.parse(env.VITE_COMPUTE_WORKLOAD_REVOKED_QUOTE_HASHES_JSON);
  } catch {
    throw new Error("live Cloudflare workload revocation set must be canonical JSON");
  }
  if (
    !Array.isArray(revoked)
    || revoked.length > 256
    || JSON.stringify(revoked) !== env.VITE_COMPUTE_WORKLOAD_REVOKED_QUOTE_HASHES_JSON
    || revoked.some((value) => !bytes32.test(String(value || "")))
    || new Set(revoked).size !== revoked.length
    || revoked.some((value, index) => index > 0 && revoked[index - 1] >= value)
  ) {
    throw new Error("live Cloudflare workload revocation set is not exact, sorted, and unique");
  }
}

function assertExactArenaChallengeSetBinding(env) {
  const approvedSetSha256 = String(
    env.VITE_ARENA_APPROVED_CHALLENGE_SET_SHA256 || "",
  );
  if (
    !/^sha256:[0-9a-f]{64}$/.test(approvedSetSha256)
    || approvedSetSha256 === `sha256:${"0".repeat(64)}`
  ) {
    throw new Error(
      "live Cloudflare release requires an exact nonzero Arena approved challenge-set SHA-256",
    );
  }
  const serializedBindings = String(
    env.VITE_ARENA_CHALLENGE_REGISTRY_BINDINGS_JSON || "",
  );
  let bindings;
  try {
    bindings = JSON.parse(serializedBindings);
  } catch {
    throw new Error(
      "live Cloudflare Arena challenge registry bindings must be canonical JSON",
    );
  }
  if (JSON.stringify(bindings) !== serializedBindings) {
    throw new Error(
      "live Cloudflare Arena challenge registry bindings must be exact compact JSON",
    );
  }
  let expected;
  try {
    expected = arenaReleaseApprovedChallengeSetSha256(bindings);
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(
      `live Cloudflare Arena challenge registry bindings are invalid: ${detail}`,
    );
  }
  if (approvedSetSha256 !== expected) {
    throw new Error(
      "live Cloudflare Arena approved challenge-set digest does not match the exact registry bindings",
    );
  }
}

export function validateSemanticValidationReceipt({ env, headSha, receipt }) {
  if (!receipt || typeof receipt !== "object" || Array.isArray(receipt)) {
    throw new Error("live Cloudflare release requires an in-process canonical semantic validation receipt");
  }
  const expectedKeys = [
    "ceremony_authorization_sha256",
    "chain_id",
    "compute_workload_activation_observation_sha256",
    "compute_workload_browser_binding_sha256",
    "deployment_intent_sha256",
    "frontend_build_candidate_receipt_sha256",
    "frontend_build_sha256",
    "live_activation_authority_sha256",
    "raw_secret_egress",
    "release_env_sha256",
    "release_inputs_sha256",
    "release_sha",
    "reviewer_authority_genesis_acceptance_sha256",
    "runtime_authority_dependency_sha256",
    "schema",
    "status",
    "truth_status",
  ];
  const actualKeys = Object.keys(receipt).sort();
  if (JSON.stringify(actualKeys) !== JSON.stringify(expectedKeys)) {
    throw new Error("live Cloudflare semantic validation receipt has an unexpected shape");
  }
  const expectedSha = clean(headSha).toLowerCase();
  if (
    receipt.schema !== SEMANTIC_VALIDATION_SCHEMA
    || receipt.status !== SEMANTIC_VALIDATION_STATUS
    || receipt.truth_status !== SEMANTIC_VALIDATION_TRUTH_STATUS
    || receipt.release_sha !== expectedSha
    || receipt.chain_id !== BASE_SEPOLIA_CHAIN_ID
    || receipt.raw_secret_egress !== false
    || [
      receipt.deployment_intent_sha256,
      receipt.reviewer_authority_genesis_acceptance_sha256,
      receipt.ceremony_authorization_sha256,
      receipt.compute_workload_activation_observation_sha256,
      receipt.compute_workload_browser_binding_sha256,
      receipt.live_activation_authority_sha256,
      receipt.runtime_authority_dependency_sha256,
      receipt.release_inputs_sha256,
      receipt.release_env_sha256,
      receipt.frontend_build_candidate_receipt_sha256,
      receipt.frontend_build_sha256,
    ].some((value) => (
      !/^sha256:[0-9a-f]{64}$/.test(String(value || ""))
      || value === `sha256:${"0".repeat(64)}`
    ))
  ) {
    throw new Error("live Cloudflare semantic validation receipt does not authorize this release");
  }
  if (
    receipt.frontend_build_candidate_receipt_sha256
      === receipt.frontend_build_sha256
  ) {
    throw new Error(
      "live Cloudflare semantic validation receipt collapses D into the dist manifest",
    );
  }
  let serialized;
  try {
    serialized = canonicalEffectiveReleaseEnv(env);
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`live Cloudflare release environment is not the canonical allowlisted output: ${detail}`);
  }
  const digest = `sha256:${createHash("sha256").update(serialized, "utf8").digest("hex")}`;
  if (receipt.release_env_sha256 !== digest) {
    throw new Error("live Cloudflare release environment does not match the semantic validation digest");
  }
  return Object.freeze({
    deploymentIntentSha256: receipt.deployment_intent_sha256,
    reviewerAuthorityGenesisAcceptanceSha256:
      receipt.reviewer_authority_genesis_acceptance_sha256,
    ceremonyAuthorizationSha256: receipt.ceremony_authorization_sha256,
    computeWorkloadActivationObservationSha256:
      receipt.compute_workload_activation_observation_sha256,
    computeWorkloadBrowserBindingSha256:
      receipt.compute_workload_browser_binding_sha256,
    liveActivationAuthoritySha256: receipt.live_activation_authority_sha256,
    runtimeAuthorityDependencySha256: receipt.runtime_authority_dependency_sha256,
    releaseInputsSha256: receipt.release_inputs_sha256,
    frontendBuildCandidateReceiptSha256:
      receipt.frontend_build_candidate_receipt_sha256,
    frontendBuildSha256: receipt.frontend_build_sha256,
    releaseEnvSha256: digest,
    serialized,
  });
}

export function cloudflareDeploymentPolicy({ env, headSha, dirty, semanticValidationReceipt }) {
  const liveRelease = cloudflareReleaseIntent(env) === "live";
  const baseArgs = [
    "pages",
    "deploy",
    "dist",
    "--project-name",
    "wikigenme",
  ];

  if (!liveRelease) {
    assertModeledEnvironmentHasNoViteOverrides(env);
    const normalizedHead = clean(headSha).toLowerCase();
    if (!/^[0-9a-f]{40}$/.test(normalizedHead)) {
      throw new Error("modeled Cloudflare preview requires the full current HEAD SHA");
    }
    return {
      mode: "modeled",
      accountId: CLOUDFLARE_ACCOUNT_ID,
      branch: CLOUDFLARE_MODELED_PREVIEW_BRANCH,
      args: [
        ...baseArgs,
        "--branch",
        CLOUDFLARE_MODELED_PREVIEW_BRANCH,
        "--commit-hash",
        normalizedHead,
        "--commit-dirty=true",
      ],
    };
  }

  const releaseSha = clean(env.VITE_RELEASE_SHA).toLowerCase();
  const normalizedHead = clean(headSha).toLowerCase();
  if (!/^[0-9a-f]{40}$/.test(releaseSha)) {
    throw new Error("a live Cloudflare release requires the full generated VITE_RELEASE_SHA");
  }
  if (releaseSha !== normalizedHead) {
    throw new Error(`live Cloudflare release SHA ${releaseSha} does not match HEAD ${normalizedHead}`);
  }
  if (clean(dirty)) {
    throw new Error("refusing to deploy a live Cloudflare release from a dirty worktree");
  }
  for (const key of REQUIRED_LIVE_FEATURE_FLAGS) {
    if (clean(env[key]) !== "true") {
      throw new Error(`live Cloudflare release requires ${key}=true from the generated release environment`);
    }
  }
  for (const key of REQUIRED_LIVE_BINDINGS) {
    if (!clean(env[key])) {
      throw new Error(`live Cloudflare release requires ${key} from the generated release environment`);
    }
  }
  exactRpcEndpoints({
    primaryRpcUrl: env.VITE_BASE_SEPOLIA_RPC_URL,
    secondaryRpcUrl: env.VITE_BASE_SEPOLIA_SECONDARY_RPC_URL,
  });
  if (clean(env.VITE_BASE_SEPOLIA_RPC_URL) !== CANONICAL_PUBLIC_RPC) {
    throw new Error(
      `live Cloudflare release requires the canonical primary RPC ${CANONICAL_PUBLIC_RPC}`,
    );
  }
  assertExactComputeWorkloadBindings(env);
  assertExactArenaChallengeSetBinding(env);
  const semanticAuthority = validateSemanticValidationReceipt({
    env,
    headSha: normalizedHead,
    receipt: semanticValidationReceipt,
  });

  return {
    mode: "live",
    frontendBuildSha256: semanticAuthority.frontendBuildSha256,
    semanticAuthority,
    accountId: CLOUDFLARE_ACCOUNT_ID,
    branch: CLOUDFLARE_PRODUCTION_BRANCH,
    args: [
      ...baseArgs,
      "--branch",
      CLOUDFLARE_PRODUCTION_BRANCH,
      "--commit-hash",
      normalizedHead,
      "--commit-dirty=false",
    ],
  };
}

export async function prepareCloudflareDeployment({
  env,
  headSha,
  dirty,
  releaseArguments = [],
  validateReleaseEnvironment,
}) {
  const intent = cloudflareReleaseIntent(env);
  if (intent === "modeled") {
    if (releaseArguments.length) {
      throw new Error("modeled Cloudflare deployment does not accept live release evidence arguments");
    }
    return cloudflareDeploymentPolicy({ env, headSha, dirty });
  }
  if (typeof validateReleaseEnvironment !== "function") {
    throw new Error("live Cloudflare release requires the canonical semantic validator");
  }
  const semanticValidationReceipt = await validateReleaseEnvironment([
    "--check-only",
    ...releaseArguments,
  ]);
  return cloudflareDeploymentPolicy({
    env,
    headSha,
    dirty,
    semanticValidationReceipt,
  });
}

